import {open,go,P,shot,btns} from "./lib.mjs";
const { browser, page } = await open("admin",{viewport:"1440"});
await go(page, P+"/pois?create=1");
await page.waitForTimeout(1000);
const d=page.getByRole("dialog");
await d.getByLabel(/Title/).first().fill("UX-R3-p1-editor Alpha POI");
await d.locator("select").nth(0).selectOption({label:"Parthenon Gallery"}).catch(async e=>{console.log("place sel fail",e.message.slice(0,100))});
await d.locator("select").nth(1).selectOption({label:"Sculpture"}).catch(e=>console.log("cat fail"));
await shot(page,"poi-create-dialog__filled__1440");
const t=Date.now();
await d.getByRole("button",{name:/Create and open/}).click();
await page.waitForURL(/pois\/[0-9a-f-]{36}/,{timeout:20000});
console.log("create->url ms",Date.now()-t, page.url());
await page.waitForLoadState("networkidle");
console.log("editor ready ms",Date.now()-t);
await page.waitForTimeout(1000);
await shot(page,"poi-editor__new-draft__1440",true);
console.log(await btns(page,"main"));
console.log((await page.evaluate(()=>document.querySelector("main").innerText)).slice(0,3500));
await browser.close();
