import {open,go,P,shot,btns,hdr,fillBasics} from "./lib.mjs";
const { browser, page } = await open("admin",{viewport:"1440"});
const mk=async(title,place,cat,img,audio)=>{
  await go(page,P+"/pois?create=1"); await page.waitForTimeout(800);
  const d=page.getByRole("dialog");
  await d.getByLabel(/Title/).first().fill(title);
  await d.locator("select").nth(0).selectOption({label:place});
  await d.locator("select").nth(1).selectOption({label:cat});
  const t=Date.now();
  await d.getByRole("button",{name:/Create and open/}).click();
  await page.waitForURL(/pois\/[0-9a-f-]{36}/,{timeout:20000});
  await page.waitForSelector("#f-title");
  console.log(title.slice(0,40),"create->editor ms",Date.now()-t,page.url().split("/").pop());
  await fillBasics(page,title.slice(15,25),{img,audio,lat:"37.97"+Math.floor(Math.random()*90+10),lon:"23.72"+Math.floor(Math.random()*90+10)});
  const t2=Date.now();
  await page.keyboard.press("Control+s");
  await page.waitForFunction(()=>/Saved \d/.test(document.body.innerText),null,{timeout:20000});
  console.log("  save ms",Date.now()-t2);
};
await mk("UX-R3-p1-editor Beta POI","Acropolis Museum","Pottery and Everyday Life","ostrakon-themistocles","audio-frieze-en");
await page.getByRole("button",{name:/^Activate/}).first().click();
await page.waitForSelector("[role=dialog]"); await page.waitForTimeout(300);
await page.getByRole("dialog").getByRole("button",{name:/Review in editor/}).click();
await page.waitForTimeout(600);
console.log("review-in-editor focus:",await page.evaluate(()=>document.activeElement.tagName+"#"+document.activeElement.id+":"+(document.activeElement.innerText||"").slice(0,40)), "dlg:",await page.getByRole("dialog").count());
await shot(page,"poi-editor__beta-after-review-in-editor__1440");
await page.getByRole("button",{name:/^Activate/}).first().click();
await page.waitForSelector("[role=dialog]");
await page.getByRole("dialog").getByRole("button",{name:/^Activate$/}).click();
await page.waitForTimeout(1500);
console.log("beta status:",await hdr(page).then(s=>s.slice(0,200)));
await mk("UX-R3-p1-editor Γάμμα POI – ένα εξαιρετικά μακρύ όνομα για δοκιμή περικοπής στη λίστα και στην κεφαλίδα του επεξεργαστή (עברית ערבית)","Parthenon Gallery","Sculpture","nike-temple","audio-peplos-kore");
await shot(page,"poi-editor__gamma-long-title__1440");
await page.getByRole("button",{name:/^Activate/}).first().click();
