console.log("apply ms",Date.now()-t);
await page.waitForTimeout(800);
console.log("toasts:",await page.evaluate(()=>[...document.querySelectorAll("li[role=status],[role=status],[role=alert]")].map(e=>e.innerText.trim().slice(0,120))));
