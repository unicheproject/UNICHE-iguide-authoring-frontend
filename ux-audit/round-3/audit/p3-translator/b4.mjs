import { open, go, base, shot } from "./lib.mjs";
import { readFileSync } from "node:fs";
const R = JSON.parse(readFileSync("ux-audit/round-3/audit/p3-translator/records.json","utf8"));
const { browser, page } = await open("admin", { viewport: "1440" });
const snap = async (label) => {
  const s = await page.evaluate(()=>{
    const tabs=[...document.querySelectorAll("[role=tab]")].map(t=>t.innerText.replace(/\s+/g," ").trim());
    const nm=[...document.querySelectorAll("button,a")].filter(b=>/Next missing/.test(b.innerText)).map(b=>{const r=b.getBoundingClientRect();return `${b.innerText.trim()} @y${Math.round(r.y+scrollY)} x${Math.round(r.x)} vis=${!!b.offsetParent}`});
    const head=[...document.querySelectorAll("header button, header [class*=badge]")].map(b=>b.innerText.trim()).filter(t=>/warning|fix|Nothing/i.test(t));
    const card=[...document.querySelectorAll("aside *")].filter(e=>e.children.length===0&&/missing|warning|fix|Nothing/i.test(e.innerText||"")).map(e=>e.innerText.trim()).slice(0,8);
    const otp=[...document.querySelectorAll("a,button")].filter(e=>/languages? incomplete|Italiano incomplete|incomplete/.test(e.innerText)).map(e=>e.innerText.replace(/\s+/g," ").trim()).slice(0,3);
    return {tabs,nm,head,card,otp};
  });
  console.log(label, JSON.stringify(s));
};
await go(page, R.pois);
await page.waitForSelector("h1"); await page.waitForTimeout(1500);
await page.locator("#f-summary").fill("A short English summary of the test sculpture.");
await page.locator("#f-description").fill("First paragraph of the English description.\nSecond paragraph, longer, to translate.");
await snap("EN filled (unsaved)");
await page.getByRole("button",{name:/^Save/}).first().click();
await page.waitForTimeout(2000);
await snap("EN saved");
await shot(page,"poi-editor__en-saved__1440",true);
