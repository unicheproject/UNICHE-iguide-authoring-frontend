await page.waitForTimeout(500);
await snap("EL after copy title");
console.log("title now:", await page.locator("#f-title").inputValue(), "| focus:", await page.evaluate(()=>document.activeElement?.id||document.activeElement?.tagName));
await page.locator("#f-title").fill("UX-R3-p3 Σημείο ενδιαφέροντος – Παρθενώνας");
await page.locator("#f-summary").fill("Σύντομη περίληψη του δοκιμαστικού γλυπτού.");
await snap("EL title+summary typed");
