import { open, go, P, shot, settle } from "./h.mjs";
const vp = "1440";
const { browser, page } = await open("admin", { viewport: vp });
await go(page, `/projects/${P}/media`); await settle(page);
const state = async (label) => { await page.waitForTimeout(900); const r = await page.evaluate(() => ({ url: location.search, count: document.querySelector("[data-media-count]")?.textContent.trim(), n: document.querySelectorAll("ul[aria-label='Media files'] > li, tbody tr").length, empty: document.querySelector("main")?.innerText.match(/No files[^\n]*/)?.[0], hint: [...document.querySelectorAll("main p")].map(p=>p.textContent.trim()).filter(t=>/match|filter/i.test(t)).slice(0,3), btn: [...document.querySelectorAll("button")].map(b=>b.textContent.trim()).filter(t=>/Filters|Clear/i.test(t)) })); console.log(label, JSON.stringify(r)); };
const open_ = async () => { if (!(await page.getByText("Needs attention").first().isVisible().catch(()=>false))) await page.getByRole("button", { name: /^Filters/ }).click(); await page.waitForTimeout(300); };
await state("base");
await open_(); await page.getByLabel("No alt text in English").check(); await state("noalt-en");
await shot(page, `lib__filter-noalt__${vp}`);
await page.locator("select").nth(1).selectOption({ label: "Audio" }).catch(async()=>{ console.log("select fail"); });
await state("audio+noalt");
await shot(page, `lib__filter-audio-noalt-empty__${vp}`);
await page.keyboard.press("Escape");
await page.getByRole("button", { name: /Clear filters/ }).first().click().catch(()=>console.log("no clear"));
await state("cleared");
await open_(); await page.locator("select").first().selectOption({ label: "Italiano" });
await state("search-in it");
const lbl = await page.evaluate(()=>[...document.querySelectorAll("label")].map(l=>l.textContent.trim()).filter(t=>/alt|transl/i.test(t)));
console.log("labels", lbl);
await page.getByLabel(/No alt text in/).check(); await state("it noalt");
await shot(page, `lib__filter-it-noalt__${vp}`);
await page.getByLabel("Needs translation").check().catch(()=>{}); await state("it noalt+needs-tr");
await page.getByLabel("Decorative").check(); await state("+decorative");
await page.getByLabel("Unused").check(); await state("+unused");
await page.getByRole("button", { name: /Newest first/ }).click(); await state("sort dir flipped");
await page.locator("select").nth(1).selectOption({ label: "Name" }); await state("sort name");
await page.reload(); await settle(page); await state("reload keeps");
await browser.close();
