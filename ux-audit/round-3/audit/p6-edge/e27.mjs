await page.route(api, async (r) => { const q = r.request(); if (q.method() === "POST" && /\/triggers$/.test(new URL(q.url()).pathname)) { const b = q.postData() || ""; posts.push(b.slice(0, 80)); if (/GEO/i.test(b)) return r.fulfill(H.problem(503, "SERVICE_UNAVAILABLE")); } return r.continue(); });
await page.getByRole("button", { name: /^Save draft/ }).first().click(); await H.sleep(2500);
log("partial trigger save", { posts, msgs: (await H.msgs(page)).filter(m=>!/^\d+ warnings/.test(m)), focus: await H.AE(page), canary: (await H.body(page)).includes(H.CANARY) });
await H.shot(page, "poi-editor__trigger-partial-failure__1440");
await page.unrouteAll({behavior:"ignoreErrors"});
await page.getByRole("button", { name: /^Save draft/ }).first().click(); await H.sleep(2500);
log("retry", { msgs: (await H.msgs(page)).filter(m=>!/^\d+ warnings/.test(m)), triggerRows: await page.locator("[id^=t-]").count() });
