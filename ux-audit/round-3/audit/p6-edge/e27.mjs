const log = H.LOG("e27");
const { browser, page } = await H.session();
const api = (u) => u.pathname.includes("/iguide/api/");
await H.go(page, H.P("/pois/" + H.ids.poi2)); await H.sleep(1800);
await page.getByRole("button", { name: /Add QR code/ }).first().click(); await H.sleep(500);
