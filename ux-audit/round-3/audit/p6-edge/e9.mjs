import * as H from "./h.mjs";
const log = H.LOG("e9");
const { browser, context, page } = await H.session();
const api = (u) => u.pathname.includes("/iguide/api/");
await H.go(page, H.P("/guides")); await H.sleep(1500);
let posts = 0;
await page.route(api, async (r) => { if (r.request().method() === "POST" && /\/guides$/.test(new URL(r.request().url()).pathname)) { posts++; await H.sleep(4000); } return r.continue(); });
await page.getByRole("button", { name: "New guide" }).first().click(); await H.sleep(600);
const dlg = page.getByRole("dialog");
await dlg.locator("input").first().fill("UX-R3-p6 dbl guide " + Date.now());
const b = dlg.getByRole("button", { name: /^Creat/ }).first();
await b.click(); await b.click({ force: true }).catch(()=>{}); await page.keyboard.press("Enter");
await H.sleep(900);
log("create double", { posts, btn: await dlg.getByRole("button").allInnerTexts(), cancelDisabled: await dlg.getByRole("button", {name:"Cancel"}).isDisabled().catch(()=>null), live: (await H.live(page)).map(x=>x.text) });
await H.shot(page, "guides-create__saving__1440");
await page.keyboard.press("Escape"); await H.sleep(400);
log("esc while creating", { dialogs: await page.getByRole("dialog").count(), msgs: await H.msgs(page) });
await H.sleep(6000);
log("after", { url: page.url().replace(H.PID,"PID"), posts, live: (await H.live(page)).map(x=>x.text) });
// Offline create
await H.go(page, H.P("/guides")); await page.unrouteAll({behavior:"ignoreErrors"}); await H.sleep(1000);
await page.getByRole("button", { name: "New guide" }).first().click(); await H.sleep(600);
await page.getByRole("dialog").locator("input").first().fill("UX-R3-p6 offline guide");
await context.setOffline(true); await H.sleep(500);
await page.getByRole("dialog").getByRole("button", { name: /^Creat/ }).first().click({force:true}); await H.sleep(1500);
log("offline create", { msgs: await H.msgs(page), focus: await H.AE(page) });
await H.shot(page, "guides-create__offline__1440");
await context.setOffline(false);
await browser.close();
