import * as H from "./h.mjs";
import { join } from "node:path";
const log = H.LOG("e23");
const { browser, page } = await H.session();
const api = (u) => u.pathname.includes("/iguide/api/");
await H.go(page, H.P("/media")); await H.sleep(1500);
await page.getByRole("button", { name: /Upload files/ }).first().click(); await H.sleep(600);
const dlg = page.getByRole("dialog");
await dlg.locator("input[type=file]").setInputFiles([join(H.here,"files","ux-r3-p6-img19.png")]); await H.sleep(3000);
await dlg.getByRole("button", { name: /Describe now/ }).click(); await H.sleep(1500);
const d2 = page.getByRole("dialog").last();
await d2.locator("textarea").fill("A purple square used as a test image.");
await page.route(api, (r) => r.request().method()==="PUT" || r.request().method()==="PATCH" ? r.fulfill(H.problem(503, "SERVICE_UNAVAILABLE")) : r.continue());
await d2.getByRole("button", { name: /Save/ }).last().click(); await H.sleep(1800);
log("describe save 503", { msgs: (await H.msgs(page)).slice(-3), focus: await H.AE(page), canary: (await H.body(page)).includes(H.CANARY) });
await H.shot(page, "describe-now__save-503__1440");
await page.unrouteAll({behavior:"ignoreErrors"});
await page.route(api, (r) => r.request().method()==="PUT" || r.request().method()==="PATCH" ? r.fulfill(H.problem(422, "VALIDATION_ERROR",{errors:[{path:"translations.en.altText",code:"TOO_LONG",message:"Alternative text must be at most 500 characters."}]})) : r.continue());
await d2.getByRole("button", { name: /Save/ }).last().click(); await H.sleep(1800);
log("describe save 422", { msgs: (await H.msgs(page)).slice(-3), focus: await H.AE(page) });
await H.shot(page, "describe-now__save-422__1440");
await browser.close();
