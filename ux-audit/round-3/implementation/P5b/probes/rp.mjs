import { session, go, P, ids, LOG, shot, sleep } from "./h.mjs";
const log = LOG("rp");
const { browser, page } = await session({ viewport: "1440" });
await go(page, P(`/events/${ids.eventEmpty}`));
await page.waitForSelector("#f-poiId", { timeout: 20000 }); await sleep(800);
const noDates = () => page.getByText("This Event has no dates").count();
log("gap before add", await noDates());
await page.locator("#occ-add").click(); await sleep(500);
log("gap after add", await noDates());
await page.getByRole("button", { name: "Repeat weekly" }).click(); await sleep(300);
await page.getByLabel("Number of weeks").fill("0"); await sleep(200);
log("count 0:", await page.locator("#occ-repeat [role=status]").last().innerText());
await page.getByLabel("Number of weeks").fill(""); await sleep(200);
log("count empty:", await page.locator("#occ-repeat [role=status]").last().innerText());
await page.getByLabel("Until a day").check();
await page.locator("#occ-repeat-until-day").fill("31"); await page.locator("#occ-repeat-until-month").selectOption("11"); await page.locator("#occ-repeat-until-year").fill("2026"); await page.locator("#occ-repeat-until-day").focus(); await sleep(300);
log("until 31 Nov:", await page.locator("#occ-repeat-until-day-error").innerText().catch(() => null), "|", await page.locator("#occ-repeat [role=status]").last().innerText());
await shot(page, "event-repeat-31nov-1440");
await browser.close();
