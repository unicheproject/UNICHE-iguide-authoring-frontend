import { session, go, P, ids, LOG, shot, sleep, AE } from "./h.mjs";
const log = LOG("b1");
const { browser, page } = await session({ viewport: "1440" });
await go(page, P(`/pois/${ids.actA}`));
await page.waitForSelector("#status-card-heading", { timeout: 20000 });
await sleep(500);
const txt = (sel) => page.evaluate((s) => [...document.querySelectorAll(s)].map((e) => e.textContent.trim().replace(/\s+/g, " ")), sel);
log("DRAFT header badge:", await txt("[data-issue-badge]"));
log("DRAFT card sentence:", await txt("[data-issue-sentence]"), "plus:", await txt("[data-plus-checks]"));
log("DRAFT lines:", await txt("#editor-side-column [data-side-card] li"));
await shot(page, "b1-draft-card-1440");
await page.getByRole("button", { name: "Activate", exact: true }).first().click();
await sleep(500);
log("CONFIRM sentences:", await txt("[role=dialog] [data-issue-sentence]"), "plus:", await txt("[role=dialog] [data-plus-checks]"));
log("CONFIRM full text:", (await page.locator("[role=dialog]").innerText()).replace(/\s+/g, " "));
log("CONFIRM count of 'warning' words:", (await page.locator("[role=dialog]").innerText()).match(/\d+ warnings?/g));
await shot(page, "b1-confirm-1440");
await page.locator("[role=dialog]").getByRole("button", { name: "Activate", exact: true }).click();
await sleep(1500);
log("TOAST:", await txt("[role=status], [data-sonner-toast], [class*=toast]"));
await shot(page, "b1-after-activate-1440");
log("ACTIVE header badge:", await txt("[data-issue-badge]"));
log("ACTIVE card sentence:", await txt("[data-issue-sentence]"));
log("ACTIVE lines:", await txt("#editor-side-column [data-side-card] li"));
log("accessibility mentions in card:", (await txt("#editor-side-column [data-side-card] li")).filter((t) => /ccessib/i.test(t)).length);
log("activeElement after activate:", await AE(page));
await browser.close();
