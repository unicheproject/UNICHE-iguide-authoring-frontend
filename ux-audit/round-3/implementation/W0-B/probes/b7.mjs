import { session, go, P, ids, LOG, shot, sleep } from "./h.mjs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../../../../../package.json", import.meta.url));
const log = LOG("b7");
const { browser, page } = await session({ viewport: "1440" });
await go(page, P(`/pois/${ids.wc1}`)); await page.waitForSelector("#f-summary"); 
await page.locator("#f-title").fill("UX-R3-W0B POI wc1 retitled " + Date.now()); await page.locator("#f-summary").fill("conflict summary " + Date.now()); await sleep(300);
const prob = (status, code, rid) => ({ status, contentType: "application/problem+json", body: JSON.stringify({ type: "x", title: "t", status, code, requestId: rid, currentVersion: 99 }) });
await page.route(/\/working-copy/, (r) => r.request().method() === "PUT" ? r.fulfill(prob(409, "VERSION_CONFLICT", "req-409-save")) : r.continue());
await page.locator("[data-banner-save]").click(); await sleep(1500);
log("WC save 409 dialog:", (await page.locator("[role=dialog]").innerText().catch(() => "NONE")).replace(/\s+/g, " "));
await shot(page, "b7-wc-save-409-1440");
await page.keyboard.press("Escape"); await sleep(300);
await page.unroute(/\/working-copy/);
await page.route(/:apply/, (r) => r.fulfill(prob(409, "VERSION_CONFLICT", "req-409-apply")));
await page.locator("[data-editor-primary]").click(); await sleep(500);
await page.locator("[role=dialog]").getByRole("button", { name: /Save and apply|Apply/ }).last().click(); await sleep(2500);
log("apply 409 dialog:", (await page.locator("[role=dialog]").innerText().catch(() => "NONE")).replace(/\s+/g, " "));
await shot(page, "b7-apply-409-1440");
await browser.close();
