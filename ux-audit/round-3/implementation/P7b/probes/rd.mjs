import { open, go, P, ids, shot } from "./h.mjs";
const { browser, page } = await open("admin", { viewport: "1440" });
await go(page, `/projects/${P}/media/${ids.one}`); await page.waitForTimeout(3500);
const side = () => page.evaluate(() => { const s = document.querySelector("#editor-side-column")?.innerText.replace(/\n+/g, " | "); return s.slice(s.indexOf("Before you activate"), s.indexOf("On thi")) ; });
const hdr = () => page.evaluate(() => document.querySelector("header + *, [data-editor-header]")?.innerText.replace(/\n+/g, " | ").slice(0, 200));
await page.locator("#f-alternativeText").fill("A blue gradient with pale circles and columns."); await page.waitForTimeout(500);
console.log("typed", await side());
await page.getByRole("button", { name: /Save draft|Save/ }).first().click(); await page.waitForTimeout(2500);
console.log("saved", await side());
console.log("tabs", await page.evaluate(() => [...document.querySelectorAll("[role=tab]")].map((t) => t.innerText.replace(/\n+/g, " "))));
await shot(page, "editor__saved__1440");
await page.getByRole("button", { name: /^Activate/ }).first().click(); await page.waitForTimeout(1200);
console.log("dialog", await page.evaluate(() => document.querySelector("[role=dialog],[role=alertdialog]")?.innerText.replace(/\n+/g, " | ")));
await shot(page, "editor__activate-confirm__1440");
await page.locator("[role=dialog] button, [role=alertdialog] button").filter({ hasText: /^Activate/ }).first().click(); await page.waitForTimeout(2000);
console.log("toast", await page.evaluate(() => [...document.querySelectorAll("[role=status],[role=alert],[data-toast]")].map((e) => e.innerText.replace(/\n+/g, " | ")).filter(Boolean)));
await shot(page, "editor__activated__1440");
console.log("after", await side());
await browser.close();
