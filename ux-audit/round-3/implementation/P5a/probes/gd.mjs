import { session, go, P, ids, LOG, shot, ax, sleep } from "./h.mjs";
const log = LOG(process.argv[2] ?? "gd");
const vp = process.argv[3] ?? "1440";
const { browser, page } = await session({ viewport: vp });
await page.addInitScript(() => {
  window.__live = [];
  const start = () => new MutationObserver((ms) => { for (const m of ms) { const t = (m.target.nodeType === 3 ? m.target.parentElement : m.target); const live = t?.closest?.("[aria-live],[role=status],[role=alert]"); const txt = live?.textContent.trim().replace(/\s+/g, " "); if (txt) window.__live.push(txt.slice(0, 160)); } }).observe(document.body, { subtree: true, childList: true, characterData: true });
  document.addEventListener("DOMContentLoaded", start);
});
const msgs = async () => { await sleep(700); return page.evaluate(() => { const r = [...new Set(window.__live)]; window.__live.length = 0; return r; }); };
await go(page, P(`/guides/${ids.guide}`));
await page.getByRole("button", { name: "Add paragraph" }).waitFor(); await sleep(1500); await msgs();
await page.getByRole("button", { name: "Add paragraph" }).click();
log("ADD paragraph live:", await msgs(), "focus:", await page.evaluate(() => document.activeElement?.id + " | " + (document.querySelector(`label[for="${document.activeElement?.id}"]`)?.textContent.trim())));
await page.keyboard.type("Intro");
await page.getByRole("button", { name: "Add heading" }).click();
log("ADD heading live:", await msgs(), "focus label:", await page.evaluate(() => document.querySelector(`label[for="${document.activeElement?.id}"]`)?.textContent.trim().replace(/\s+/g, " ")));
await page.keyboard.type("Title two");
await page.getByRole("button", { name: "Add reference" }).click(); await sleep(400);
const dlg = page.getByRole("dialog", { name: "Add a reference" });
await dlg.getByRole("searchbox").fill("παρθενωνας"); await sleep(300);
log("reference picker παρθενωνας rows", await dlg.locator("ul li").count());
await dlg.locator("ul li button").first().click(); await sleep(600);
log("PICK reference live:", await msgs());
log("labels", await page.evaluate(() => [...document.querySelectorAll("[data-element-row] label")].map((l) => l.textContent.trim())));
log("reference link rect", await page.evaluate(() => { const a = document.querySelector("[data-element-row] a[href*=poi]"); const r = a?.getBoundingClientRect(); return r && [Math.round(r.width), Math.round(r.height)]; }));
await page.getByRole("button", { name: /^Move heading 2 up|Move heading \(block 2\) up|Move .*up/ }).nth(1).click().catch(() => {});
log("MOVE live:", await msgs());
await page.getByRole("button", { name: /^Remove heading/ }).first().click();
log("REMOVE live:", await msgs());
log("bar text", await page.evaluate(() => document.querySelector("[data-removed-bar] [role=status]")?.textContent));
await page.evaluate(() => document.getElementById("story").scrollIntoView()); await sleep(500);
await shot(page, `guide-${vp}`);
log(vp, "axe", await ax(page));
await browser.close();
