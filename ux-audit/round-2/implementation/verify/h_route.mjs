import { open, CMS, P, settle, here } from "./lib.mjs";
import { join } from "node:path";
const base = `${CMS}/projects/${P}`;
const { browser, page } = await open("admin", { viewport: "1440" });
const log = console.log;
const act = () => page.evaluate(() => { const a = document.activeElement; return `${a?.tagName.toLowerCase()} "${(a?.getAttribute("aria-label") || a?.textContent || "").trim().replace(/\s+/g," ").slice(0, 70)}"`; });
await page.goto(`${base}/routes`); await settle(page, 1200);
await page.getByRole("searchbox").first().fill("UX-R2-verify"); await page.waitForTimeout(1200);
await page.getByRole("link", { name: /UX-R2-verify Route/ }).first().click(); await settle(page, 1800);
await page.getByRole("button", { name: /Add stops/i }).first().click(); await page.waitForTimeout(1200);
const rows = page.getByRole("dialog").getByRole("option");
log("picker options", await rows.count());
await page.screenshot({ path: join(here, "shots", "1440-route-picker.png") });
await page.getByText("Acropolis View Terrace").first().click(); await page.getByText("Altar of the Twelve Gods").first().click(); await page.waitForTimeout(500);
await page.getByRole("button", { name: /^Done/ }).click(); await page.waitForTimeout(800);
const stops = () => page.getByRole("button", { name: /Remove (stop|Acropolis|Altar)|^Remove/i });
log("stops after add:", await stops().count(), "focus", await act());
await stops().first().click(); await page.waitForTimeout(800);
log("after remove: stops", await stops().count(), "focus:", await act());
await page.screenshot({ path: join(here, "shots", "1440-route-undo-bar.png") });
await page.keyboard.press("Control+z"); await page.waitForTimeout(800);
log("after Ctrl+Z: stops", await stops().count(), "focus:", await act());
await browser.close();
