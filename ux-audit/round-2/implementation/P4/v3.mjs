import { open, go } from "../../../tools/session.mjs";
import { readFileSync } from "node:fs";
const P = "6958c18f-60d2-4140-a524-5a43f8a2f6b5";
const r = JSON.parse(readFileSync("records.json", "utf8"));
const log = (...a) => console.log(...a);
const { browser, page } = await open("admin", { viewport: "1440" });
const calls = [];
page.on("request", (q) => { if (/\/triggers/.test(q.url()) && q.method() !== "GET") calls.push({ t: Date.now(), m: q.method(), u: q.url().split("/triggers")[1] || "", b: q.postData()?.slice(0, 80) }); });
await go(page, `/projects/${P}/pois/${r.poi}`);
await page.waitForSelector("[data-sticky-bar]", { timeout: 30000 }); await page.waitForTimeout(2000);
await page.getByRole("button", { name: /^Add Beacon/ }).click();
await page.getByRole("button", { name: /^Add Geo-proximity/ }).click();
await page.getByRole("button", { name: /^Add QR code/ }).click();
const row = (n) => page.locator("[data-trigger-row]").nth(n);
await row(0).getByLabel("UUID").fill("e2c56db5-dffb-48d2-b060-d0f5a71096e0");
await row(0).getByLabel("Major").fill("1"); await row(0).getByLabel("Minor").fill("2");
await row(1).getByLabel("Latitude").fill("37.9715"); await row(1).getByLabel("Longitude").fill("23.7257");
let fail = true;
await page.route("**/triggers", async (route) => {
  const req = route.request();
  if (fail && req.method() === "POST" && /BEACON/.test(req.postData() ?? "")) return route.fulfill({ status: 503, contentType: "application/problem+json", body: JSON.stringify({ code: "SERVICE_UNAVAILABLE", status: 503, title: "x", requestId: "req-test-1" }) });
  return route.continue();
});
await page.getByRole("button", { name: /^Save$|^Save draft$/ }).first().click();
await page.waitForTimeout(4000);
log("calls:", JSON.stringify(calls.map((c) => c.m + " " + c.u + " " + (c.b ?? "").slice(0, 50))));
log("start spread ms:", calls.length ? calls.at(-1).t - calls[0].t : 0);
log("summary:", (await page.locator("[data-editor-summary]").allInnerTexts()).join("|") || (await page.locator("[role=alert]").allInnerTexts()).join("|"));
log("state line:", await page.evaluate(() => document.body.innerText.match(/Unsaved changes|Saved \d\d:\d\d/)?.[0]));
log("rows kept:", await page.locator("[data-trigger-row]").count());
await page.screenshot({ path: "after/partial-1440.png" });
fail = false; calls.length = 0;
await page.getByRole("button", { name: /^Save$|^Save draft$/ }).first().click();
await page.waitForTimeout(3500);
log("second save calls:", JSON.stringify(calls.map((c) => c.m + " " + c.u)));
log("state line:", await page.evaluate(() => document.body.innerText.match(/Unsaved changes|Saved \d\d:\d\d/)?.[0]), "rows", await page.locator("[data-trigger-row]").count());
await page.screenshot({ path: "after/triggers-saved-1440.png" });
await browser.close();
