import { open, go, PID, shot, fs } from "./lib.mjs";
const ids = JSON.parse(fs.readFileSync(new URL("./ids.json", import.meta.url)));
const { browser, page } = await open("curator", { viewport: "1440" });
const tabs = async () => (await page.locator("[role=tab]").evaluateAll(e => e.map(x => x.innerText.replace(/\n/g," ")))).join(" / ");
const head = async () => (await page.locator("main").innerText()).split("\n").slice(0,12).join(" / ");
await go(page, `/projects/${PID}/pois/${ids.poi2}`);
await page.waitForFunction(() => document.querySelector("h1")?.innerText.includes("UX-R2"), null, { timeout: 40000 }).catch(()=>{}); await page.waitForTimeout(2000);
await page.getByRole("button", { name: "Activate", exact: true }).click(); await page.waitForTimeout(1200);
await shot(page, "poi-active__activate-dialog");
console.log("dialog:", (await page.locator("[role=dialog], [role=alertdialog]").first().innerText()).replace(/\n+/g," | ").slice(0,500));
await page.locator("[role=dialog] button, [role=alertdialog] button").filter({ hasText: /^Activate/ }).last().click(); await page.waitForTimeout(3000);
console.log("after activate:", await head());
await shot(page, "poi-active__after-activate");
// translate Italian on ACTIVE
await page.getByRole("tab", { name: /Italiano/ }).click(); await page.waitForTimeout(500);
await page.getByLabel("Title in Italiano").fill("UX-R2-p3 Sala dei Kouroi");
await page.getByLabel("Summary in Italiano").fill("Giovani in piedi del VI secolo a.C.");
await page.getByLabel("Description in Italiano").fill("Una sala silenziosa di kouroi in marmo.");
console.log("tabs:", await tabs(), "| head:", await head());
await shot(page, "poi-active__it-typed");
await page.keyboard.press("Control+s"); await page.waitForTimeout(3000);
console.log("after ctrl+s head:", await head());
await shot(page, "poi-active__after-save-pending");
console.log("banner:", (await page.locator("[role=status], [data-working-copy], section:has-text('pending')").allInnerTexts()).join(" || ").replace(/\n+/g," ").slice(0,500));
await page.reload(); await page.waitForTimeout(3000);
await page.getByRole("tab", { name: /Italiano/ }).click(); await page.waitForTimeout(500);
console.log("after reload head:", await head(), "| tabs:", await tabs(), "| it title:", await page.getByLabel("Title in Italiano").inputValue());
await shot(page, "poi-active__reload");
await browser.close();
