import { open, go, shot, P, settle } from "./lib.mjs";
const { browser, page } = await open("curator", { viewport: "1440" });
await go(page, `/projects/${P}/pois`);
await page.getByRole("button", { name: /new point of interest/i }).click();
const d = page.getByRole("dialog");
await d.getByLabel(/^Title/).fill("UX-R2-p1-editor Amphora Room");
await d.getByLabel("Place").selectOption({ label: "Parthenon Gallery" }).catch(async e => { console.log("place sel err", e.message.slice(0,100)); });
await d.getByLabel("Category").selectOption({ label: "Sculpture" });
const t0 = Date.now();
await d.getByRole("button", { name: /create and open/i }).click();
await page.waitForURL(/pois\/[0-9a-f-]{36}/);
await page.getByRole("heading", { level: 1 }).first().waitFor();
await settle(page, 1500);
console.log("create->editor ms", Date.now()-t0, page.url());
console.log("focus:", await page.evaluate(() => document.activeElement?.outerHTML.slice(0,120)), "title:", await page.title());
await shot(page, "poi-editor__new-draft__1440");
await shot(page, "poi-editor__new-draft-full__1440", true);
console.log("pageheight", await page.evaluate(() => document.documentElement.scrollHeight));
console.log(await page.locator("body").innerText());
await browser.close();
