import { open, go, P, ids, shot, settle, alerts, focused, main, problem, AP } from "./lib.mjs";
const PP = `/projects/${P}`;
const { browser, page } = await open("curator", { viewport: "1440" });
const dlg = () => page.locator("[role=dialog],[role=alertdialog]").first();
await go(page, `${PP}/pois`); await settle(page, 900);
await page.getByRole("button", { name: /New point/ }).first().click(); await page.waitForTimeout(600);
await dlg().locator("input[type=text]").first().fill("UX-R2-p6 Double submit POI");
let posts = 0;
await page.route(AP, async (r) => { if (r.request().method() === "POST") { posts++; await new Promise(s => setTimeout(s, 3500)); } return r.continue(); });
const create = dlg().getByRole("button", { name: /^Create/ });
const t0 = Date.now();
await create.dblclick(); await page.keyboard.press("Enter"); await page.waitForTimeout(300);
console.log("btn text during", JSON.stringify(await dlg().getByRole("button").allInnerTexts()), "alerts", JSON.stringify(await alerts(page)).slice(0,200));
await shot(page, "poi-create__submitting");
await page.keyboard.press("Escape"); await page.waitForTimeout(300);
console.log("Esc during submit: dialog still?", await page.locator("[role=dialog]").count());
await page.waitForTimeout(5000);
console.log("POST count", posts, "url", page.url().slice(-50));
// Activate double-submit: use POI Alpha editor? activate via forced slow status POST on poiA
await page.unroute(AP);
const I = ids();
await go(page, `${PP}/pois/${I.poiA}`); await settle(page, 800);
await page.evaluate(() => localStorage.clear());
let st = 0;
await page.route(AP, async (r) => { if (r.request().method() === "POST" && /status/.test(r.request().url())) { st++; await new Promise(s => setTimeout(s, 3500)); return r.fulfill(problem(422, "NOT_READY", { errors: [{ path: "", code: "X", message: "Not ready." }] })); } return r.continue(); });
await page.getByRole("button", { name: /^Activate$|Save and activate/ }).first().click(); await page.waitForTimeout(700);
console.log("ACT dialog:", (await dlg().innerText()).replace(/\n+/g," | ").slice(0,400));
await shot(page, "poi-activate__confirm");
const go2 = dlg().getByRole("button", { name: /activate/i }).last();
await go2.dblclick(); await page.keyboard.press("Enter"); await page.waitForTimeout(500);
console.log("ACT during:", JSON.stringify(await dlg().getByRole("button").allInnerTexts()));
await shot(page, "poi-activate__submitting");
await page.waitForTimeout(4500);
console.log("status POSTs", st, "dialog now:", (await dlg().innerText().catch(()=>"(none)")).replace(/\n+/g," | ").slice(0,400), "| focus", await focused(page));
await shot(page, "poi-activate__refused-422");
await browser.close();
