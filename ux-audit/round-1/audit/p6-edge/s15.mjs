import { open, go, P, shot, log, alerts, focused, problem } from "./lib.mjs";
import { readFileSync } from "node:fs";
const ids = JSON.parse(readFileSync("ux-audit/round-1/audit/p6-edge/ids.json","utf8"));
const { browser, context, page } = await open("curator", { viewport: "1440" });
page.on("dialog", d=>d.accept());
const dlgText = async () => (await page.locator("[role=dialog],[role=alertdialog]").first().innerText().catch(()=>"(no dialog)")).replace(/\n+/g," | ").slice(0,900);
const url = `/projects/${P}/pois/${ids.poiC}`;
await go(page, url); await page.waitForTimeout(1000);
const disc = page.getByRole("button",{name:"Discard"}); if (await disc.count()) await disc.first().click().catch(()=>{});
await page.locator("#f-title").fill("UX-p6-edge POI C applied once");
let n = []; 
await page.route("**/iguide/api/v1/**", async (route) => { const r=route.request(); if (r.method()!=="GET") { n.push(r.method()+" "+r.url().split("/pois")[1]); await new Promise(x=>setTimeout(x,6000)); } return route.continue(); });
await page.getByRole("button",{name:/apply changes/i}).first().click(); await page.waitForTimeout(400);
const confirm = page.locator("[role=dialog] button").filter({hasText:/apply changes/i}).first();
await confirm.click(); await confirm.click({force:true,timeout:500}).catch(()=>log("2nd click blocked")); await confirm.dblclick({force:true,timeout:500}).catch(()=>{});
await page.waitForTimeout(1000);
log("in-flight dialog", await dlgText(), "btns", (await page.getByRole("button").allTextContents()).map(s=>s.trim()).filter(x=>/apply|saving|appl|sav/i.test(x)));
await shot(page, "poi-apply__in-flight__1440");
await page.waitForTimeout(7000);
log("requests", n, "alerts", await alerts(page), "focus", await focused(page));
await shot(page, "poi-apply__done__1440");
await page.unrouteAll({behavior:"ignoreErrors"});
// Apply with forced 409
await page.locator("#f-title").fill("UX-p6-edge POI C apply conflict");
await page.route("**/iguide/api/v1/**", (route) => { const r=route.request(); return r.method()!=="GET" ? route.fulfill(problem(409,"VERSION_CONFLICT",{currentVersion: 9, conflictingFields:["translations.en.title"]})) : route.continue(); });
await page.getByRole("button",{name:/apply changes/i}).first().click(); await page.waitForTimeout(400);
await page.locator("[role=dialog] button").filter({hasText:/apply changes/i}).first().click(); await page.waitForTimeout(1500);
log("APPLY-409 dialog:", await dlgText(), "alerts", await alerts(page), "focus", await focused(page));
await shot(page, "poi-apply__409__1440");
await browser.close();
