import { open, go, P, shot, log, alerts, focused } from "./lib.mjs";
import { readFileSync } from "node:fs";
const ids = JSON.parse(readFileSync("ux-audit/round-1/audit/p6-edge/ids.json","utf8"));
const creds = JSON.parse(readFileSync("ux-audit/tools/accounts.local","utf8")).curator;
const { browser, context, page } = await open("curator", { viewport: "1440" });
const url = `/projects/${P}/pois/${ids.poiB}`;
await go(page, url); await page.waitForTimeout(1000);
await page.locator("#f-title").fill("UX-p6-edge POI B typed before expiry");
await page.locator("#f-summary").fill("Summary typed before the session died.");
await page.getByText("Practical details").first().click().catch(()=>{});
await page.waitForTimeout(500);
await context.clearCookies();
await page.route("**/iguide/api/v1/**", (route) => route.request().method()==="PUT" ? route.fulfill({status:401, contentType:"application/problem+json", body: JSON.stringify({status:401,code:"UNAUTHORIZED",title:"Unauthorized"})}) : route.continue());
await page.getByRole("button",{name:"Save",exact:true}).first().click();
await page.waitForURL(/\/realms\//, {timeout:20000}).catch(()=>log("no redirect to login"));
await page.waitForTimeout(1500);
log("url", page.url().slice(0,80));
await shot(page, "session-expired__login__1440");
await page.locator("#username").fill(creds.user); await page.locator("#password").fill(creds.password); await page.locator("#kc-login").click();
await page.waitForURL(u=>!u.toString().includes("/realms/"), {timeout:30000});
await page.unrouteAll({behavior:"ignoreErrors"});
await page.waitForLoadState("networkidle").catch(()=>{}); await page.waitForTimeout(2000);
log("back at", page.url());
await shot(page, "poi-editor__after-login-draft__1440");
log("banner", await page.getByText("Unsaved changes from").count(), "title", await page.locator("#f-title").inputValue(), "summary", await page.locator("#f-summary").inputValue());
await page.getByRole("button",{name:"Restore"}).click(); await page.waitForTimeout(800);
log("after restore title", await page.locator("#f-title").inputValue(), "summary", await page.locator("#f-summary").inputValue(), "focus", await focused(page), "alerts", await alerts(page));
await shot(page, "poi-editor__after-restore__1440");
// reload to check discard path
await page.reload(); await page.waitForLoadState("networkidle"); await page.waitForTimeout(1500);
log("after reload banner", await page.getByText("Unsaved changes from").count());
await page.getByRole("button",{name:"Discard"}).click(); await page.waitForTimeout(800);
log("after discard alerts", await alerts(page), "title", await page.locator("#f-title").inputValue(), "focus", await focused(page));
await shot(page, "poi-editor__after-discard__1440");
await browser.close();
