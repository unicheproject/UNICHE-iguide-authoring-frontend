import { open, go, P, shot, log, alerts, focused } from "./lib.mjs";
import { readFileSync } from "node:fs";
const ids = JSON.parse(readFileSync("ux-audit/round-1/audit/p6-edge/ids.json","utf8"));
const a = await open("curator", { viewport: "1440" });
const b = await open("curator", { viewport: "1440" });
const url = `/projects/${P}/pois/${ids.poiB}`;
await go(a.page, url); await go(b.page, url); await a.page.waitForTimeout(1000); await b.page.waitForTimeout(1000);
await a.page.locator("#f-title").fill("UX-p6-edge POI B from A");
await a.page.locator("#f-summary").fill("Summary from A");
await a.page.getByRole("button",{name:"Save",exact:true}).first().click(); await a.page.waitForTimeout(2000);
log("A alerts", await alerts(a.page));
await b.page.locator("#f-title").fill("UX-p6-edge POI B from B");
await b.page.locator("#f-summary").fill("Summary from B");
await b.page.locator("#f-description").fill("Description only in B");
await b.page.getByRole("button",{name:"Save",exact:true}).first().click(); await b.page.waitForTimeout(2500);
log("B alerts", await alerts(b.page)); log("B focus", await focused(b.page));
await shot(b.page, "poi-editor__409-conflict__1440");
await shot(b.page, "poi-editor__409-conflict-full__1440", true);
log("B main", (await b.page.locator("main").innerText()).replace(/\n+/g," | ").slice(0,1500));
log("buttons", (await b.page.getByRole("button").allTextContents()).map(s=>s.trim()).filter(Boolean).slice(0,20));
await a.browser.close(); await b.browser.close();
