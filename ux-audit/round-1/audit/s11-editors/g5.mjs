import { start, goP, log, dump, state, focused } from "./lib.mjs";
const s = await start("1440"); const { page } = s;
await page.goto("http://localhost:5173" + state().guideUrl); await page.waitForTimeout(3000);
await page.getByRole("button", { name: /preview in app/i }).first().click(); await page.waitForTimeout(2500);
await s.shot("guide-preview-in-app");
log("preview dialog:", await page.locator("[role=dialog]").count(), (await dump(page,"[role=dialog]").catch(()=>"")).slice(0,300));
log("focus:", await focused(page));
await page.keyboard.press("Escape"); await page.waitForTimeout(500);
log("after esc focus:", await focused(page), "dialogs", await page.locator("[role=dialog]").count());
await page.getByRole("button", { name: /^activate$/i }).click(); await page.waitForTimeout(2500);
log("alerts", await page.evaluate(()=>[...document.querySelectorAll("[role=alert],[role=status]")].map(e=>e.innerText.slice(0,200))));
await s.shot("guide-activated");
await page.getByLabel(/^title/i).first().fill("UX-s11-editors Guide v2"); await page.waitForTimeout(300);
await page.getByRole("button", { name: /^Remove paragraph 5/i }).click().catch(()=>log("no rm 5")); await page.waitForTimeout(400);
await s.shot("guide-wc-dirty");
await page.evaluate(()=>document.querySelector("main")?.scrollTo(0,0));
await page.getByRole("button", { name: /save draft/i }).click(); await page.waitForTimeout(2000);
await page.reload(); await page.waitForTimeout(3000);
await s.shot("guide-wc-after-reload");
log("restore banner?", await page.getByRole("button", { name: /restore/i }).count());
await s.browser.close();
